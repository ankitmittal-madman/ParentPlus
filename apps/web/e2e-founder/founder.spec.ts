import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
test("founder uses dummy OTP, saves real records and controls test access", async ({ page, context }) => {
  await context.route("**/*", route => ["http://127.0.0.1:3193", "http://127.0.0.1:54321"].includes(new URL(route.request().url()).origin) ? route.continue() : route.abort());
  await page.goto("/founder");
  await page.getByRole("button", { name: "Refresh test records" }).click();
  const count = async (name: string) => Number(await page.getByText(name, { exact: true }).locator("..").locator("dd").innerText());
  const before = { children: await count("children"), courses: await count("courses"), batches: await count("batches"), sessions: await count("schedule sessions") };
  const email = `founder-${randomUUID()}@example.test`;
  await page.goto("/login");
  await expect(page.getByText(/Founder sandbox:/)).toBeVisible();
  await page.getByLabel("Email address").fill(email);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Verification code").fill("000000");
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Founder sign-in is unavailable" })).toBeVisible();
  await page.getByLabel("Verification code").fill("123456");
  await page.getByRole("button", { name: "Verify code", exact: true }).click();
  await expect(page.getByText("Signed in.", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "View profiles you created" }).click();
  await page.getByRole("button", { name: "Check creation status", exact: true }).click();
  await page.getByLabel("Child name").fill("Fictional Founder Child");
  await page.getByRole("button", { name: "Create profile", exact: true }).click();
  await page.getByRole("button", { name: "Confirm result", exact: true }).click();
  await page.getByRole("button", { name: "Load profiles", exact: true }).click();
  await expect(page.getByRole("listitem").filter({ hasText: "Fictional Founder Child" })).toHaveCount(1);
  await page.goto("/coach-onboarding");
  await page.getByRole("button", { name: "Check workspace setup", exact: true }).click();
  await page.getByLabel("Workspace name").fill(`Founder Academy ${email.slice(8,16)}`);
  await page.getByRole("button", { name: "Create workspace", exact: true }).click();
  await page.getByRole("link", { name: "Continue to class setup" }).click();
  const setup = page.getByRole("region", { name: "Check class setup", exact: true });
  await setup.getByRole("button", { name: "Load academies", exact: true }).click();
  await setup.getByLabel("Academy", { exact: true }).selectOption({ index: 1 });
  await setup.getByLabel("Course name", { exact: true }).fill("Founder Clay Basics");
  await setup.getByLabel("Batch name", { exact: true }).fill("Founder Juniors");
  await setup.getByLabel("Academy time zone", { exact: true }).fill("Asia/Kolkata");
  await setup.getByLabel("First session date").fill("2026-11-16");
  await setup.getByLabel("Local start time").fill("17:00");
  await setup.getByLabel("Last date for weekly sessions").fill("2026-11-30");
  await setup.getByRole("button", { name: "Create course, batch and weekly sessions", exact: true }).click();
  await expect(setup.getByText("Weekly schedule: 3 sessions", { exact: true })).toBeVisible();
  await setup.getByRole("button", { name: "Confirm course, batch and schedule", exact: true }).click();
  await page.goto("/founder");
  await page.getByRole("button", { name: "Refresh test records" }).click();
  expect(await count("children")).toBe(before.children + 1);
  expect(await count("courses")).toBe(before.courses + 1);
  expect(await count("batches")).toBe(before.batches + 1);
  expect(await count("schedule sessions")).toBe(before.sessions + 3);
  await page.getByLabel("Test account").selectOption({ label: email });
  await page.getByLabel("Test workspace").selectOption({ label: `Founder Academy ${email.slice(8,16)}` });
  await page.getByLabel("Role", { exact: true }).selectOption("owner");
  await page.getByLabel("Access status").selectOption("suspended");
  await page.getByRole("button", { name: "Apply test access" }).click();
  await expect(page.getByRole("status")).toContainText("Test membership updated");
  await page.goto("/schedule"); await expect(page).toHaveURL(/\/coach-access$/);
  await page.goto("/founder"); await page.getByRole("button", { name: "Refresh test records" }).click();
  await page.getByLabel("Test account").selectOption({ label: email });
  await page.getByLabel("Test workspace").selectOption({ label: `Founder Academy ${email.slice(8,16)}` });
  await page.getByLabel("Role", { exact: true }).selectOption("owner");
  await page.getByRole("button", { name: "Apply test access" }).click();
  await expect(page.getByRole("status")).toContainText("Test membership updated");
  await page.goto("/schedule"); await expect(page.getByRole("heading", { name: "Schedule", exact: true })).toBeVisible();
  await setup.getByRole("button", { name: "Load academies", exact: true }).click();
  await setup.getByLabel("Academy", { exact: true }).selectOption({ index: 1 });
  await expect(setup.getByText("Course: Founder Clay Basics", { exact: true })).toBeVisible();
  await expect(setup.getByText("Weekly schedule: 3 sessions", { exact: true })).toBeVisible();
});
